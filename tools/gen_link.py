#!/usr/bin/env python3
"""Generate `PureInterp/Image/LinkIncluded.lean` and `LinkTable.lean` from the
already generated image (`Index.lean`, `Text*.lean`, `Data.lean`).

  python3 tools/gen_link.py PureInterp/Image

Nothing here is trusted: every emitted statement is checked by Lean's kernel
against the image definitions. The script only decides which statements to
write down (the position of each function in `Image.functions`, and the name
of the function each instruction-table entry points to).
"""
import glob
import re
import sys

TABLE_ADDR = 0xA0000150  # monad::vm::interpreter::instruction_table<...>, see build/pure.map


def main(d):
    index = open(f"{d}/Index.lean").read()
    names = re.findall(r"^  \((\w+)\.addr, \1\.prog\),", index, re.M)
    addr = {}
    for f in glob.glob(f"{d}/Text*.lean"):
        for n, a in re.findall(r"^def (\w+)\.addr : Word := 0x([0-9a-f]+)", open(f).read(), re.M):
            addr[n] = int(a, 16)
    assert len(names) == len(addr), (len(names), len(addr))
    by_addr = {a: n for n, a in addr.items()}

    data = open(f"{d}/Data.lean").read()
    base = int(re.search(r"def data0\.addr : Word := 0x([0-9a-f]+)", data).group(1), 16)
    bs = [int(x) for x in re.search(r"def data0\.bytes[^\[]*\[([^\]]*)\]", data).group(1).split(",")]
    off = TABLE_ADDR - base
    assert off % 8 == 0 and off + 8 * 256 <= len(bs)
    entries = [int.from_bytes(bytes(bs[off + 8 * i: off + 8 * i + 8]), "little") for i in range(256)]
    targets = [by_addr[e] for e in entries]

    out = [
        "-- GENERATED by `tools/gen_link.py`; do not edit.",
        "import PureInterp.Image.Link",
        "",
        "/-! Every function of the image is included in `imageCode`. -/",
        "",
        "open RiscvZkvm.Rv64",
        "",
        "namespace PureInterp.Image",
        "",
    ]
    for k, n in enumerate(names):
        out.append(
            f"theorem {n}.included : ∀ a i, CodeReq.ofProg {n}.addr {n}.prog a = some i → "
            f"imageCode a = some i :=\n  included_of_index (k := {k}) rfl\n")
    out.append("end PureInterp.Image\n")
    open(f"{d}/LinkIncluded.lean", "w").write("\n".join(out))

    invalid = [i for i, t in enumerate(targets) if t == "f_invalid"]
    out = [
        "-- GENERATED by `tools/gen_link.py`; do not edit.",
        "import PureInterp.Image.LinkTable",
        "",
        "/-! The contents of the instruction table, entry by entry. -/",
        "",
        "set_option maxRecDepth 100000",
        "",
        "open RiscvZkvm.Rv64",
        "",
        "namespace PureInterp.Image",
        "",
        "/-- The handler each opcode byte dispatches to. -/",
        "def tableTargets : List Word := [",
    ]
    for i in range(0, 256, 4):
        out.append("  " + " ".join(f"{t}.addr," for t in targets[i:i + 4]) + f" -- 0x{i:02x}")
    out[-1] = out[-1].replace(".addr, --", ".addr] --")
    out += [
        "",
        "/-- The table read from the data segment is the table of handler addresses. -/",
        "theorem imageTable_eq : imageTable = tableTargets := by decide",
        "",
        "/-- The opcode bytes whose table entry is the `invalid` handler. -/",
        "def invalidOpcodes : List Nat := [",
    ]
    for i in range(0, len(invalid), 16):
        out.append("  " + ", ".join(f"0x{v:02x}" for v in invalid[i:i + 16]) + ",")
    out[-1] = out[-1][:-1] + "]"
    out += [
        "",
        f"theorem invalidOpcodes_length : invalidOpcodes.length = {len(invalid)} := rfl",
        "",
        "theorem tableTargets_length : tableTargets.length = 256 := rfl",
        "",
        "/-- Every entry is an even address, in the form `JALR`'s target computation needs. -/",
        "theorem imageTable_aligned : ∀ i, i < 256 →",
        "    (imageTable.getD i 0 + signExtend12 0x000#12) &&& ~~~1 = imageTable.getD i 0 := by",
        "  rw [imageTable_eq]; decide",
        "",
        "/-- Every entry is a multiple of 4. -/",
        "theorem imageTable_aligned4 : ∀ i, i < 256 → imageTable.getD i 0 &&& 3 = 0 := by",
        "  rw [imageTable_eq]; decide",
        "",
        "/-- Exactly the opcodes in `invalidOpcodes` dispatch to the `invalid` handler. -/",
        "theorem imageTable_invalid_iff (n : Nat) :",
        "    imageTable.getD n 0 = f_invalid.addr ↔ n ∈ invalidOpcodes := by",
        "  rw [imageTable_eq]",
        "  by_cases h : n < 256",
        "  · exact (by decide : ∀ m, m < 256 →",
        "      (tableTargets.getD m 0 = f_invalid.addr ↔ m ∈ invalidOpcodes)) n h",
        "  · have h0 : tableTargets.getD n 0 = 0 := by",
        "      rw [List.getD_eq_getElem?_getD, List.getElem?_eq_none (by rw [tableTargets_length]; omega)]",
        "      rfl",
        "    have hlt : ∀ m, m ∈ invalidOpcodes → m < 256 := by decide",
        "    rw [h0]",
        "    exact ⟨fun e => absurd e (by decide), fun hm => absurd (hlt n hm) h⟩",
        "",
    ]
    for i, t in enumerate(targets):
        out.append(f"theorem imageTable_0x{i:02x} : imageTable.getD 0x{i:02x} 0 = {t}.addr := by\n"
                   f"  rw [imageTable_eq]; rfl\n")
    out.append("end PureInterp.Image\n")
    open(f"{d}/LinkTableEntries.lean", "w").write("\n".join(out))
    print(f"{len(names)} functions, {len(invalid)} invalid table entries, "
          f"{len(set(targets))} distinct handlers")


if __name__ == "__main__":
    main(sys.argv[1])
